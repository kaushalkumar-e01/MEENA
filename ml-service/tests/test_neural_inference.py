"""
Unit Test Suite for MEENA Neural Inference Engine & API Integration

Verifies:
1. Checkpoint loading and 1-Encoder + 13-Decoder restoration.
2. Tokenizer compatibility and special token alignment.
3. Actual neural response generation from trained weights.
4. Multi-turn conversation context formatting and handling.
5. Anti-repetition penalty and n-gram blocking.
6. Safe CPU fallback capability.
7. Missing checkpoint error handling.
8. FastAPI /ml/meena-generate and /ml/meena-status endpoint integration.
"""

import sys
import os
import unittest
import torch
from fastapi.testclient import TestClient

# Ensure ml-service is in sys.path
BASE_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if BASE_DIR not in sys.path:
    sys.path.insert(0, BASE_DIR)

from meena_inference import MeenaInferenceEngine, HONEST_FALLBACK_RESPONSE


class TestNeuralInference(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.ckpt_path = os.path.join(BASE_DIR, "checkpoints", "checkpoint_best.pt")
        cls.tokenizer_dir = os.path.join(BASE_DIR, "data", "tokenizer")

    def test_01_checkpoint_loading(self):
        """Test 1: Verify checkpoint_best.pt loads and restores 1 enc + 13 dec layers."""
        engine = MeenaInferenceEngine.get_instance(checkpoint_path=self.ckpt_path, force_reload=True)
        self.assertIsNotNone(engine.model)
        self.assertEqual(len(engine.model.encoder.layers), 1, "Expected exactly 1 encoder block")
        self.assertEqual(len(engine.model.decoder.layers), 13, "Expected exactly 13 decoder blocks")
        self.assertFalse(engine.model.training, "Model should be in eval() mode")

    def test_02_tokenizer_compatibility(self):
        """Test 2: Verify tokenizer matches model embedding dimensions and special tokens."""
        engine = MeenaInferenceEngine.get_instance()
        tokenizer = engine.tokenizer
        self.assertEqual(tokenizer.pad_token_id, 0)
        self.assertEqual(tokenizer.bos_token_id, 1)
        self.assertEqual(tokenizer.eos_token_id, 2)
        self.assertEqual(tokenizer.unk_token_id, 3)
        self.assertEqual(engine.model.shared_embedding.num_embeddings, tokenizer.get_vocab_size())

    def test_03_actual_neural_response_generation(self):
        """Test 3: Verify response is generated by the neural network weights."""
        engine = MeenaInferenceEngine.get_instance()
        result = engine.generate(
            prompt="What is an API in simple terms?",
            max_new_tokens=30,
            temperature=0.65
        )
        self.assertIn("response", result)
        self.assertIn("tokens_generated", result)
        self.assertGreater(result["tokens_generated"], 0)
        self.assertIsInstance(result["response"], str)
        self.assertGreater(len(result["response"]), 0)
        self.assertEqual(result["model"], "MEENA Evolved Transformer (1 Enc + 13 Dec)")

    def test_04_conversation_context(self):
        """Test 4: Verify multi-turn history is properly structured for the model."""
        engine = MeenaInferenceEngine.get_instance()
        history = [
            {"role": "user", "content": "Hello MEENA!"},
            {"role": "assistant", "content": "Hello! How can I help you today?"}
        ]
        context = engine.build_context(prompt="I need advice on managing stress.", history=history)
        self.assertIn("User: Hello MEENA!", context)
        self.assertIn("MEENA: Hello! How can I help you today?", context)
        self.assertIn("User: I need advice on managing stress.", context)

        # Generate response with context
        result = engine.generate(
            prompt="I need advice on managing stress.",
            history=history,
            max_new_tokens=25
        )
        self.assertIsInstance(result["response"], str)
        self.assertGreater(len(result["response"]), 0)

    def test_05_repetition_penalty_effectiveness(self):
        """Test 5: Verify repetition penalty suppresses degenerate repeated tokens."""
        engine = MeenaInferenceEngine.get_instance()
        result = engine.generate(
            prompt="Tell me about yourself.",
            max_new_tokens=35,
            temperature=0.6,
            repetition_penalty=1.4,
            no_repeat_ngram_size=3
        )
        words = result["response"].split()
        # Ensure no token is repeated 4+ times consecutively
        max_consecutive = 1
        curr_consecutive = 1
        for i in range(1, len(words)):
            if words[i].lower() == words[i-1].lower():
                curr_consecutive += 1
                max_consecutive = max(max_consecutive, curr_consecutive)
            else:
                curr_consecutive = 1
        self.assertLess(max_consecutive, 3, f"Detected excessive consecutive repetition: {max_consecutive}")

    def test_06_cpu_fallback(self):
        """Test 6: Verify engine functions on CPU when CUDA is disabled."""
        engine_cpu = MeenaInferenceEngine(
            checkpoint_path=self.ckpt_path,
            device="cpu"
        )
        self.assertEqual(engine_cpu.device.type, "cpu")
        result = engine_cpu.generate(
            prompt="Good morning!",
            max_new_tokens=15,
            temperature=0.6
        )
        self.assertIsInstance(result["response"], str)
        self.assertEqual(result["device"], "cpu")

    def test_07_missing_checkpoint_handling(self):
        """Test 7: Verify missing checkpoint raises FileNotFoundError with clean message."""
        with self.assertRaises(FileNotFoundError):
            MeenaInferenceEngine(
                checkpoint_path=os.path.join(BASE_DIR, "checkpoints", "non_existent_ckpt.pt")
            )

    def test_08_api_meena_status(self):
        """Test 8: Verify GET /ml/meena-status endpoint returns model architecture status."""
        from main import get_meena_status
        data = get_meena_status()
        self.assertEqual(data.get("status"), "ready")
        self.assertEqual(data.get("encoder_blocks"), 1)
        self.assertEqual(data.get("decoder_blocks"), 13)
        self.assertEqual(data.get("model_architecture"), "1_encoder_13_decoder_evolved_transformer")

    def test_09_api_meena_generate(self):
        """Test 9: Verify POST /ml/meena-generate endpoint serves neural inference."""
        from main import generate_meena_response, MeenaGenerateRequest
        payload = MeenaGenerateRequest(
            prompt="What is database normalization?",
            history=[],
            temperature=0.65,
            max_new_tokens=25
        )
        data = generate_meena_response(payload)
        self.assertIsNotNone(data.response)
        self.assertEqual(data.model, "MEENA Evolved Transformer (1 Enc + 13 Dec)")
        self.assertGreater(len(data.response), 0)


if __name__ == "__main__":
    unittest.main()

